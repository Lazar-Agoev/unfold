//! TypeScript generation for the command table (decision U-25): every payload type's
//! declaration (from its `ts_rs::TS` derive), the `Commands` map (name → `{ args, result,
//! stream? }`), the `Events` map keyed by `type`, and the sink and error shapes, as one module
//! the UI, the preload script, and the engine host import. `cargo xtask gen-ipc` writes it to
//! `ui/src/ipc/generated/index.ts`; `--check` fails when the file is stale.
//!
//! Output is deterministic: declarations are sorted by name and commands keep table order. Two
//! different Rust types with one TypeScript name are an error, never a silent overwrite.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

use ts_rs::{Config, TS, TypeVisitor};

use crate::events::WorkspaceEvent;
use crate::host::SinkMessage;
use crate::ipc::error::CommandError;
use crate::ipc::table::specs;
use crate::registry::OpenedFolder;

/// The generated module's path, relative to the repository root.
pub const OUTPUT_PATH: &str = "ui/src/ipc/generated/index.ts";

/// One command, as the generator sees it.
pub struct CommandSpec {
    /// The command's name.
    pub name: &'static str,
    /// Its documentation, one line per doc line.
    pub docs: &'static str,
    /// The TypeScript type of its arguments.
    pub args: fn(&Config) -> String,
    /// The TypeScript type of its result.
    pub result: fn(&Config) -> String,
    /// The TypeScript type of its stream messages, for a streamed command.
    pub stream: Option<fn(&Config) -> String>,
    /// Adds the declarations its types need.
    pub visit: fn(&mut Collector),
}

/// The TypeScript name of `T`.
pub fn ts_name<T: TS + ?Sized>(config: &Config) -> String {
    T::name(config)
}

/// Collects the declarations of types and everything they reference.
pub struct Collector {
    config: Config,
    seen: HashSet<TypeId>,
    declarations: BTreeMap<String, (TypeId, String)>,
    clashes: Vec<String>,
}

impl Collector {
    fn new() -> Self {
        Self {
            config: config(),
            seen: HashSet::new(),
            declarations: BTreeMap::new(),
            clashes: Vec::new(),
        }
    }

    /// Adds `T` (when it has a declaration) and every type it references.
    pub fn add<T: TS + 'static + ?Sized>(&mut self) {
        self.visit::<T>();
        T::visit_generics(self);
    }
}

impl TypeVisitor for Collector {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let name = T::ident(&self.config);
            let mut declaration = T::docs().unwrap_or_default();
            declaration.push_str("export ");
            declaration.push_str(&T::decl(&self.config));
            match self.declarations.get(&name) {
                // A shadowing implementation (`serde_json::Value` as `JsonValue`) declares the
                // same text under another type ID; only different declarations clash.
                Some((other, text)) if *other != TypeId::of::<T>() && *text != declaration => {
                    self.clashes.push(name);
                }
                Some(_) => {}
                None => {
                    self.declarations.insert(name, (TypeId::of::<T>(), declaration));
                }
            }
        }
        T::visit_dependencies(self);
    }
}

/// The settings every declaration is generated with: 64-bit integers are plain numbers (no
/// count or size Unfold sends comes near 2^53).
fn config() -> Config {
    Config::new().with_large_int("number")
}

/// The generated module's text, or the names two Rust types both claim.
pub fn generate() -> Result<String, String> {
    let specs = specs();
    let mut collector = Collector::new();
    for spec in &specs {
        (spec.visit)(&mut collector);
    }
    collector.add::<OpenedFolder>();
    collector.add::<WorkspaceEvent>();
    collector.add::<SinkMessage>();
    collector.add::<CommandError>();
    if !collector.clashes.is_empty() {
        return Err(format!(
            "several Rust types generate the TypeScript names {}",
            collector.clashes.join(", ")
        ));
    }
    let config = &collector.config;
    let mut out = String::new();
    out.push_str(
        "// GENERATED by `cargo xtask gen-ipc` from the command table in crates/unfold-workspace.\n\
         // Do not edit by hand: change the Rust types and run `cargo xtask gen-ipc` again.\n\
         /* eslint-disable */\n\n",
    );
    for (_, declaration) in collector.declarations.values() {
        out.push_str(declaration.trim_end());
        out.push_str("\n\n");
    }
    out.push_str("/** Every engine command: its arguments, its result, and, for a streamed command, its stream messages. */\n");
    out.push_str("export interface Commands {\n");
    for spec in &specs {
        out.push_str("  /**\n");
        for line in spec.docs.lines() {
            let _ = writeln!(
                out,
                "   *{}",
                if line.is_empty() {
                    String::new()
                } else {
                    format!(" {}", line.trim())
                }
            );
        }
        out.push_str("   */\n");
        let _ = write!(
            out,
            "  {}: {{ args: {}; result: {}",
            spec.name,
            (spec.args)(config),
            (spec.result)(config)
        );
        if let Some(stream) = spec.stream {
            let _ = write!(out, "; stream: {}", stream(config));
        }
        out.push_str(" };\n");
    }
    out.push_str("}\n\n");
    out.push_str(
        "/** A command's name. */\n\
         export type CommandName = keyof Commands;\n\n\
         /** A command's arguments. */\n\
         export type CommandArgs<C extends CommandName> = Commands[C][\"args\"];\n\n\
         /** A command's result. */\n\
         export type CommandResult<C extends CommandName> = Commands[C][\"result\"];\n\n\
         /** The commands that stream messages before their result. */\n\
         export type StreamCommandName = {\n  [C in CommandName]: Commands[C] extends { stream: unknown } ? C : never;\n}[CommandName];\n\n\
         /** A streamed command's message. */\n\
         export type StreamMessage<C extends StreamCommandName> = Commands[C] extends { stream: infer M } ? M : never;\n\n\
         /** An engine event's `type`. */\n\
         export type EventType = WorkspaceEvent[\"type\"];\n\n\
         /** Every engine event, keyed by its `type`. */\n\
         export type Events = { [E in WorkspaceEvent as E[\"type\"]]: E };\n\n",
    );
    out.push_str("/** Every command name, in table order. */\nexport const COMMAND_NAMES = [\n");
    for spec in &specs {
        let _ = writeln!(out, "  \"{}\",", spec.name);
    }
    out.push_str("] as const satisfies readonly CommandName[];\n\n");
    out.push_str("/** The commands that stream messages. */\nexport const STREAM_COMMANDS = [\n");
    for spec in specs.iter().filter(|spec| spec.stream.is_some()) {
        let _ = writeln!(out, "  \"{}\",", spec.name);
    }
    out.push_str("] as const satisfies readonly StreamCommandName[];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_every_command_and_event() {
        let text = generate().expect("generate");
        for name in crate::ipc::table::Request::NAMES {
            assert!(text.contains(&format!("  {name}: {{ args: ")), "{name}");
        }
        assert!(text.contains("export type WorkspaceEvent ="));
        assert!(text.contains("\"board_conflict\""));
        assert!(
            text.contains("compile: { args: CompileArgs; result: CompileOutcome; stream: CompileProgress }")
        );
        assert!(!text.contains("bigint"));
        assert_eq!(text, generate().expect("again"), "generation is deterministic");
    }
}
