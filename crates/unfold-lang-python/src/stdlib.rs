/// Whether `root` (a module's first part) is in the standard library.
pub fn is_stdlib_root(root: &str) -> bool {
    STDLIB_ROOTS.binary_search(&root).is_ok()
}

/// The module label of an external module specifier: `python:<root>` for the standard library
/// and `builtins`, else the specifier's first part.
pub fn module_label(specifier: &str) -> String {
    let root = specifier.split('.').next().unwrap_or(specifier);
    if root == "builtins" || is_stdlib_root(root) {
        format!("python:{root}")
    } else {
        root.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_inventory_is_sorted_and_pinned() {
        assert!(STDLIB_ROOTS.windows(2).all(|pair| pair[0] < pair[1]));
        assert_eq!(STDLIB_ROOTS.len(), 283);
        for root in ["__future__", "asyncio", "cProfile", "json", "typing", "zoneinfo"] {
            assert!(is_stdlib_root(root), "{root}");
        }
        assert!(!is_stdlib_root("fastapi"));
    }

    #[test]
    fn labels_name_the_first_part() {
        assert_eq!(module_label("os.path"), "python:os");
        assert_eq!(module_label("builtins"), "python:builtins");
        assert_eq!(module_label("celery.schedules"), "celery");
        assert_eq!(module_label("uvicorn"), "uvicorn");
    }
}
